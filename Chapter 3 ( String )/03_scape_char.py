# Escape sequence char

print('''Twinkle,\nTwinkle,\nLittle \nStar,  
How I wonder what you are.
Up above the world so high, ''') # \n do line break

print('''Twinkle,\tTwinkle,\tLittle \tStar,  
How I wonder what you are.
Up above the world so high, ''') # \t do tab space

print('''\"Twinkle, Twinkle, Little, Star,  
How I wonder what you are.
Up above the world so high\"; ''') # \" insert quotes in line 